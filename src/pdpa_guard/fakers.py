def s_name(rng, ctx=None):
    if rng.random() < 0.13:
        title = rng.choice(["", "", "Mr. ", "Ms. ", "Mrs. ", "Khun "])
        return _pii(f"{title}{rng.choice(EN_FIRST)} {rng.choice(EN_LAST)}", "name")
    g = rng.choice("mfu")
    pool = MALE_FIRST if g == "m" else FEMALE_FIRST if g == "f" else UNISEX_FIRST
    first = rng.choice(pool)
    last = rng.choice(SURNAMES)
    r = rng.random()
    if r < 0.40:
        text = f"{rng.choice(TITLES[g])}{first} {last}"
    elif r < 0.55:
        text = f"คุณ{first} {last}"
    elif r < 0.85:
        text = f"{first} {last}"
    elif r < 0.93:
        text = f"{first} ({rng.choice(NICKNAMES)}) {last}"
    else:
        text = f"{rng.choice(TITLES[g])}{first}"
    return _pii(text, "name")


