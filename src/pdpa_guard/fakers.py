import re
import string

REF_YEAR = 2026  # CE "today" used for ages and dates

_A2T = str.maketrans("0123456789", "๐๑๒๓๔๕๖๗๘๙")
_T2A = str.maketrans("๐๑๒๓๔๕๖๗๘๙", "0123456789")
_SEP = re.compile(r"[\s\-]")
DIGITS = "0123456789"
UPPER = string.ascii_uppercase
ALNUM = string.ascii_letters + DIGITS


# ----------------------------------------------------------------------------- helpers
def normalize_digits(s) -> str:
    """Thai digits -> Arabic digits."""
    return str(s).translate(_T2A)


def _strip_seps(s) -> str:
    return _SEP.sub("", normalize_digits(s))


def _digits(rng: random.Random, n: int) -> str:
    return "".join(rng.choice(DIGITS) for _ in range(n))


def _rand_str(rng: random.Random, pool: str, n: int) -> str:
    return "".join(rng.choice(pool) for _ in range(n))


def _maybe_th(s: str, rng: random.Random, p: float = 0.04) -> str:
    """Occasionally render the digits in Thai numerals."""
    return s.translate(_A2T) if rng.random() < p else s


def _pii(text: str, typ: str, **extra):
    span = {"type": typ, "value": text}
    span.update(extra)
    return text, [span]


def _none(text: str):
    return text, []


# ----------------------------------------------------------------------------- Thai ID / Luhn / cards
def _id_check_digit(first12: str) -> int:
    total = sum(int(c) * (12 - i) for i, c in enumerate(first12))
    return (11 - total % 11) % 10


def is_valid_thai_id(s) -> bool:
    t = _strip_seps(s)
    if len(t) != 13 or not (t.isascii() and t.isdigit()):
        return False
    return _id_check_digit(t[:12]) == int(t[12])


def make_thai_id(rng: random.Random) -> str:
    first = rng.choices("12345678", weights=[40, 15, 10, 10, 8, 7, 5, 5])[0]
    body = first + _digits(rng, 11)
    return body + str(_id_check_digit(body))


def make_invalid_id(rng: random.Random) -> str:
    good = make_thai_id(rng)
    bad = (int(good[12]) + rng.randint(1, 9)) % 10
    return good[:12] + str(bad)


def luhn_ok(s) -> bool:
    t = _strip_seps(s)
    if len(t) < 2 or not (t.isascii() and t.isdigit()):
        return False
    total = 0
    for i, ch in enumerate(reversed(t)):
        d = int(ch)
        if i % 2:
            d = d * 2 - 9 if d * 2 > 9 else d * 2
        total += d
    return total % 10 == 0


def _luhn_complete(body15: str) -> str:
    for c in DIGITS:
        if luhn_ok(body15 + c):
            return body15 + c
    raise AssertionError("unreachable")


def make_card(rng: random.Random, brand=None) -> str:
    brand = brand or rng.choice(["visa", "visa", "mastercard", "jcb"])
    if brand == "visa":
        prefix = "4"
    elif brand == "mastercard":
        if rng.random() < 0.5:
            prefix = str(rng.randint(51, 55))
        else:
            prefix = str(rng.randint(2221, 2720))
    elif brand == "jcb":
        prefix = str(rng.randint(3528, 3589))
    else:
        raise ValueError(f"unknown brand {brand!r}")
    body = prefix + _digits(rng, 15 - len(prefix))
    return _luhn_complete(body)


def make_invalid_card(rng: random.Random) -> str:
    good = make_card(rng)
    bad = (int(good[-1]) + rng.randint(1, 9)) % 10
    return good[:-1] + str(bad)


def _group(d: str, rng: random.Random, size: int = 4) -> str:
    r = rng.random()
    if r < 0.4:
        return " ".join(d[i:i + size] for i in range(0, len(d), size))
    if r < 0.75:
        return "-".join(d[i:i + size] for i in range(0, len(d), size))
    return d


