"""Synthetic value generators ("fakers") for the PDPA-guard dataset.

Stdlib only. Every value is synthetic. All randomness comes from the random.Random
instance passed in (the global random module is never used), so output is
deterministic for a given seed.

Public API: gen_slot, SLOTS, is_valid_thai_id, luhn_ok, normalize_digits,
make_thai_id, make_invalid_id, make_card, make_invalid_card.
"""
from __future__ import annotations

